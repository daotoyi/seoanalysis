export function resolveLanguage(preference = "auto") {
  if (preference === "zh" || preference === "en") return preference;
  const browserLanguage =
    typeof navigator !== "undefined" ? navigator.languages?.[0] || navigator.language || "en" : "en";
  return browserLanguage.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function t(language, key, params = {}) {
  const resolved = resolveLanguage(language);
  const template = messages[resolved][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) =>
    params[name] === undefined ? `{${name}}` : String(params[name])
  );
}

export function translateError(error, language) {
  const code = error?.code || "UNKNOWN";
  const key = `error.${code}`;
  const params = {};
  if (code === "SAVE_LIMIT") params.limit = error?.limit || 20;
  const translated = t(language, key, params);
  return translated === key ? error?.message || t(language, "error.UNKNOWN") : translated;
}

export function applyTranslations(root, language) {
  const resolved = resolveLanguage(language);
  if (root?.documentElement) root.documentElement.lang = resolved === "zh" ? "zh-CN" : "en";
  else if (root?.setAttribute) root.setAttribute("lang", resolved === "zh" ? "zh-CN" : "en");

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(resolved, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(resolved, element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", t(resolved, element.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(resolved, element.dataset.i18nAriaLabel));
  });
  return resolved;
}

export function nextLanguagePreference(currentPreference) {
  const current = resolveLanguage(currentPreference);
  return current === "zh" ? "en" : "zh";
}

export function translationKeys(language) {
  return Object.keys(messages[resolveLanguage(language)]);
}
